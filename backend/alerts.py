import smtplib
import threading
import json
import urllib.request
from email.mime.text import MIMEText
from email.mime.multipart import MIMEMultipart
from config import Config
from routes.event_routes import broadcast_event

def send_email_alert_async(recipient_email, subject, body_html):
    """Sends email alert in background thread so API response is never blocked."""
    if not recipient_email or not Config.SMTP_SERVER:
        print(f"[Alert Simulator] Email to '{recipient_email}': {subject}")
        return

    def _worker():
        try:
            msg = MIMEMultipart("alternative")
            msg["Subject"] = subject
            msg["From"] = Config.ALERT_EMAIL_FROM
            msg["To"] = recipient_email

            part = MIMEText(body_html, "html")
            msg.attach(part)

            with smtplib.SMTP(Config.SMTP_SERVER, Config.SMTP_PORT, timeout=5) as server:
                server.starttls()
                if Config.SMTP_USER and Config.SMTP_PASSWORD:
                    server.login(Config.SMTP_USER, Config.SMTP_PASSWORD)
                server.sendmail(Config.ALERT_EMAIL_FROM, [recipient_email], msg.as_string())
            print(f"[Alerts] Email successfully sent to {recipient_email}")
        except Exception as e:
            print(f"[Alerts Warning] Failed to send email alert: {e}")

    threading.Thread(target=_worker, daemon=True).start()

def trigger_webhook_async(payload):
    """Triggers an external webhook (Slack, Teams, IoT buzzer gateway) asynchronously."""
    if not Config.ALERT_WEBHOOK_URL:
        return

    def _worker():
        try:
            data = json.dumps(payload).encode("utf-8")
            req = urllib.request.Request(
                Config.ALERT_WEBHOOK_URL,
                data=data,
                headers={"Content-Type": "application/json"}
            )
            with urllib.request.urlopen(req, timeout=4) as resp:
                pass
        except Exception as e:
            print(f"[Alerts Warning] Webhook notification failure: {e}")

    threading.Thread(target=_worker, daemon=True).start()

def dispatch_violation_alert(event_doc, supervisor_alert):
    """
    Unified alert dispatch:
    1. Real-time SSE to web dashboard
    2. Email notification to shift supervisor
    3. External webhook if configured
    """
    # 1. SSE Broadcast
    broadcast_event("VIOLATION_DETECTED", {
        "event": event_doc,
        "alert": supervisor_alert
    })

    # 2. Email alert to supervisor
    if supervisor_alert and supervisor_alert.get("supervisorEmail"):
        zone_name = supervisor_alert.get("zoneName", "Monitored Zone")
        missing_ppe = ", ".join(supervisor_alert.get("missingPPE", ["Mandatory Gear"]))
        subject = f"⚠️ PPE Violation Detected - {zone_name}"
        html_body = f"""
        <div style="font-family: sans-serif; padding: 20px; background-color: #0f172a; color: #f8fafc; border-radius: 8px;">
            <h2 style="color: #ef4444; margin-top: 0;">🚨 Workplace Safety Alert: PPE Violation</h2>
            <p><strong>Zone:</strong> {zone_name}</p>
            <p><strong>Missing Equipment:</strong> <span style="color: #fca5a5;">{missing_ppe}</span></p>
            <p><strong>Time:</strong> {supervisor_alert.get('timestamp')}</p>
            {f'<p><strong>Evidence:</strong> <a href="{event_doc.get("imageUrl")}" style="color: #38bdf8;">View Captured Snapshot</a></p>' if event_doc.get("imageUrl") else ''}
            <hr style="border-color: #334155; margin: 20px 0;" />
            <p style="font-size: 12px; color: #94a3b8;">Automated message generated by AI PPE Compliance Vision System.</p>
        </div>
        """
        send_email_alert_async(supervisor_alert["supervisorEmail"], subject, html_body)

    # 3. Webhook notification
    trigger_webhook_async({
        "eventType": "PPE_VIOLATION",
        "zoneName": supervisor_alert.get("zoneName") if supervisor_alert else "Monitored Zone",
        "missingPPE": supervisor_alert.get("missingPPE", []) if supervisor_alert else [],
        "evidenceUrl": event_doc.get("imageUrl")
    })
